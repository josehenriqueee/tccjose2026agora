            <h1>Política de privacidade</h1>
            <p>Esta página explica, de forma resumida, quais informações são usadas pelo D20REALITAS para oferecer os recursos da plataforma.</p>

            <h2>Informações utilizadas</h2>
            <p>No cadastro, o sistema solicita nome, e-mail e senha. A senha é armazenada em formato protegido por hash. O sistema também pode guardar informações que você adiciona ao usar seus recursos, como dados de fichas, campanhas e inventários.</p>

            <h2>Como as informações são utilizadas</h2>
            <p>As informações são utilizadas para criar e identificar sua conta, permitir o acesso às funcionalidades e guardar os dados necessários para o funcionamento das fichas e campanhas.</p>

            <h2>Sessão e armazenamento</h2>
            <p>Ao entrar na conta, o site utiliza uma sessão para manter seu acesso durante a navegação. Os dados da conta e do conteúdo criado são armazenados pelo sistema para que os recursos possam funcionar.</p>

            <h2>Compartilhamento e segurança</h2>
            <p>Não insira informações pessoais sensíveis em fichas ou campanhas. O sistema adota proteção de senha por hash, mas nenhum serviço online pode garantir segurança absoluta. Esta página não afirma a utilização de serviços externos específicos; consulte a administração para obter informações sobre a hospedagem e o tratamento técnico dos dados.</p>

            <h2>Seus direitos e contato</h2>
            <p>Você pode solicitar informações, correção ou exclusão dos dados associados à sua conta entrando em contato pelo endereço informado no rodapé. O atendimento dependerá da confirmação da titularidade e das obrigações aplicáveis.</p>

            <h2>Atualizações</h2>
            <p>Esta política pode ser atualizada quando o funcionamento do sistema mudar. Consulte esta página para verificar a versão vigente.</p>
